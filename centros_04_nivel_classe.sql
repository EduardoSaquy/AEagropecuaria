select 1 as ordem, 'Centros com classe' as item,
       (count(*) filter (where classe is not null))::text as valor,
       (count(*) filter (where classe is not null) || ' de ' || count(*)) as situacao
from centros_custo
union all
select 2, 'Classes distintas', count(distinct classe)::text, 'no Conag sao 40'
from centros_custo where classe is not null
union all
select 3, 'Total dos lancamentos', round(sum(valor),2)::text,
       'tem que continuar 10447812.29'
from lancamentos_financeiros
union all
select 4, 'SEM CLASSE: ' || c.nome,
       count(l.id)::text,
       'R$ ' || coalesce(round(sum(l.valor),2), 0)::text || ' | ' || coalesce(c.subcategoria,'sem grupo')
from centros_custo c
left join lancamentos_financeiros l on l.centro_custo_id = c.id
where c.classe is null
group by c.nome, c.subcategoria
order by ordem, item;
