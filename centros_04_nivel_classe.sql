-- A comparacao ignora acento, caixa e espaco repetido: nossos nomes vieram
-- de importacao e nem sempre batem caractere a caractere com a tela deles.
-- unaccent em vez de translate com a tabela de acentos escrita a mao: o
-- arquivo fica sem um unico caractere acentuado, e o separador de
-- statements do editor do Supabase nao tem como se perder nele.
create extension if not exists unaccent;

create or replace function normaliza_conta(t text) returns text
language sql immutable as $$
  select upper(btrim(regexp_replace(
    unaccent(coalesce(t,'')), '[[:space:]]+', ' ', 'g')));
$$;


